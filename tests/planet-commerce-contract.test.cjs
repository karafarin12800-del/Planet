"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
(async()=>{
 const source=fs.readFileSync(require("node:path").join(__dirname,"..","cloudflare-commerce-worker/index.js"),"utf8");
 const schema=fs.readFileSync(require("node:path").join(__dirname,"..","cloudflare-commerce-worker/schema.sql"),"utf8");
 const encoded=Buffer.from(source).toString("base64");
 const mod=await import("data:text/javascript;base64,"+encoded);
 const catalog=mod.planets();
 assert.equal(catalog.length,100);
 assert.equal(new Set(catalog.map(x=>x.id)).size,100);
 assert.equal(new Set(catalog.map(x=>x.name)).size,100);
 assert.ok(catalog.every(x=>x.price>=150&&x.price<=1000));
 assert.equal(catalog[0].id,"planet-001");
 assert.equal(catalog[99].id,"planet-100");
 assert.equal(mod.TOKEN_PRODUCT,"planet_tokens_200");
 assert.equal(mod.TOKEN_GRANT,200);
 assert.equal(mod.WELCOME_GRANT,20);
 assert.ok(source.includes('path===" /planets/buy"'.replace(" ", "")),"server-priced planet purchase endpoint exists");
 assert.ok(source.includes('path===" /market/cancel"'.replace(" ", "")),"seller can cancel an active listing");
 assert.ok(schema.includes("UNIQUE(owner_id,client_key)"),"specimen sync is idempotent per account");
 assert.ok(schema.includes("CREATE TABLE IF NOT EXISTS planet_ownership"),"purchased planet ownership persists in D1");
 assert.ok(source.includes('path==="/profile"'),"players can read and choose a public display name");
 assert.ok(source.includes('path==="/planets/owners"'),"planet ownership has a public display-name lookup");
 assert.ok(source.includes("DISPLAY_NAME_TAKEN"),"public display names are unique");
 assert.ok(source.includes("claims.nonce!==nonce"),"Google nonce must match the signed ID token");
 assert.ok(source.includes("BAZAAR_RECEIPT_ALREADY_USED"),"a receipt cannot be replayed into another account");
 assert.ok(source.includes("pardakht.cafebazaar.ir/devapi/v2/auth/token/"),"Bazaar access tokens are refreshed server-side");
 assert.ok(source.includes("pardakht.cafebazaar.ir/devapi/v2/api/validate/"),"receipt validation uses the Developer API v2 endpoint");
 assert.ok(source.includes('authorization:"Bearer "+tokenData.access_token'),"Bazaar access token is sent as a bearer credential");
 assert.ok(source.includes("Number(receipt.purchaseState)!==0"),"only successful purchase state is credited");
 assert.ok(!source.includes("receipt.productId!==TOKEN_PRODUCT"),"product identity is bound to the official validation URL path");
 assert.ok(source.includes("claims.nonce!==nonce"),"Google nonce must match the signed ID token");
 assert.ok(source.includes("BAZAAR_RECEIPT_ALREADY_USED"),"a receipt cannot be replayed into another account");
 console.log("Planet commerce catalog and token contract tests passed.");
})().catch(error=>{console.error(error);process.exit(1);});
