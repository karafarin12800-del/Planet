"use strict";
const assert=require("node:assert/strict");
const Genome=require("../evolution-engine.js");
global.PlanetEvolutionModel=Genome;
const Life=require("../planet-autonomous-evolution.js");
global.PlanetAutonomousEvolution=Life;
const Game=require("../planet-genome-game.js");
const planet={id:"system-04-p2",name:"آوید",type:"terrestrial",meanTemperatureC:22,waterCoverage:.55,gravity:1.1,atmosphere:"nitrogen-rich"};
const earth=Life.createEarthGenomePool(20261109);
const dayA=Game.createDailyPool("account-world-A","2026-11-09",earth);
const dayB=Game.createDailyPool("account-world-A","2026-11-10",earth);
const playerB=Game.createDailyPool("account-world-B","2026-11-09",earth);
assert.equal(dayA.length,4);
assert.ok(dayA.every(x=>Game.validDNA(x.dna)));
assert.notDeepEqual(dayA.map(x=>x.dna),dayB.map(x=>x.dna),"daily source genomes rotate by date");
assert.notDeepEqual(dayA.map(x=>x.dna),playerB.map(x=>x.dna),"players receive different daily genome selections");
const worldA=Game.createWorld("server-random-seed-A",planet,dayA.map(x=>x.dna));
const worldB=Game.createWorld("server-random-seed-B",planet,dayA.map(x=>x.dna));
assert.equal(worldA.species.length,2,"an off-world biosphere starts with two founders");
assert.notEqual(worldA.rng,worldB.rng,"different account+planet seeds produce different ecosystems");
Game.advance(worldA,240);
assert.ok(worldA.species.length>2&&worldA.species.length<=24,"off-world ecosystem can produce additional distinct species");
const parents=worldA.species.slice(0,2),child=Game.breed(worldA,parents[0],parents[1]);
assert.ok(Game.validDNA(child.dna));
assert.equal(child.generation,Math.max(parents[0].generation,parents[1].generation)+1);
assert.ok(child.bodyLengthCm>=Game.MIN_SIZE_CM&&child.bodyLengthCm<=Game.MAX_SIZE_CM);
assert.ok(["موش‌مانند","گربه‌مانند","سگ‌مانند","اسب‌مانند","فیل‌مانند"].includes(child.sizeLabel));
const restored=Game.restore(Game.save(worldA));
assert.equal(restored.year,worldA.year);assert.ok(restored.species.length<=24);
assert.equal(Genome.normalizeSyntheticGenome(child.dna),child.dna);
console.log("Planet Genome Game tests passed:",{daily:dayA.length,worldSpecies:worldA.species.length,hybrid:child.sizeLabel});
