"use strict";
const assert=require("node:assert/strict");
const commerce=require("../planet-collection-commerce.js");
const storage={data:new Map(),getItem(k){return this.data.has(k)?this.data.get(k):null;},setItem(k,v){this.data.set(k,v);}};
const world="system-01-p1";
const baseSpecies={id:6,nameFa:"گونهٔ پایه",dna:"ATGCGTAA",form:"چهاراندام",generation:1,fitness:.5,habitat:"shore",bodyLengthCm:30,special:false,originWorldType:"earth"};
assert.throws(()=>commerce.acquire(state,baseSpecies,world),/میکروسکوپی|۲ سانتی‌متر/);
const species={id:7,nameFa:"شکارچی آبی",dna:"ATGCGTAA",form:"چهاراندام",generation:12,fitness:.8,habitat:"shore",parentId:3,bodyLengthCm:65,special:true,rarityScore:90,originWorldType:"earth"};
let state=commerce.load(storage,world);
assert.equal(state.credits,250);
const first=commerce.acquire(state,species,world);
assert.ok(first.id&&first.id!==String(species.id));
assert.equal(first.speciesId,7);
assert.equal(first.source,"evolution");
assert.equal(commerce.save(storage,world,state),true);
state=commerce.load(storage,world);
assert.equal(state.specimens.length,1);
assert.equal(state.specimens[0].dna,species.dna);
const baseIneligible={...first,id:"base-specimen",special:false,bodyLengthCm:65};state.specimens.push(baseIneligible);
assert.equal(commerce.specimenValue(baseIneligible),0);assert.throws(()=>commerce.sell(state,baseIneligible.id),/قابل فروش|اجازهٔ فروش/);
state.specimens=state.specimens.filter(x=>x.id!==baseIneligible.id);
const sale=commerce.sell(state,first.id);
assert.ok(sale.price>0);
assert.equal(state.specimens.length,0,"selling removes the owned specimen permanently");
assert.equal(state.credits,250+sale.price);
assert.throws(()=>commerce.sell(state,first.id),/دیگر در کلکسیون نیست/,"a sold specimen cannot be sold twice");
const reacquired=commerce.acquire(state,species,world);
assert.notEqual(reacquired.id,first.id,"reacquisition creates a new specimen identity");
const bought=commerce.buyCreature(state,{...species,id:8,nameFa:"گونهٔ بازار"},world,80);
assert.equal(bought.specimen.source,"market");
assert.equal(state.credits,250+sale.price-80);
const item=commerce.SHOP_ITEMS()[0];
const purchase=commerce.buyItem(state,item.id);
assert.ok(state.ownedItems.includes(item.id));
assert.equal(purchase.credits,state.credits);
assert.throws(()=>commerce.buyItem(state,item.id),/قبلاً خریداری شده/,"cosmetic entitlements cannot be duplicated");
const other=commerce.load(storage,"system-02-p1");
assert.equal(other.specimens.length,0,"collections are isolated by planet");
assert.equal(other.credits,250);
console.log("Planet collection and local commerce tests passed.");
