"use strict";
const assert = require("node:assert/strict");
const engine = require("../evolution-engine.js");
const life = require("../planet-autonomous-evolution.js");
assert.equal(life.selfTest().ok, true);
const state = life.createState(99);
assert.equal(state.species.length, 4);
life.advanceYears(state, 2000);
assert.equal(state.year, 2000);
assert.ok(state.species.length >= 4);
assert.ok(state.species.length <= 36, "species catalog remains bounded during long runs");
assert.ok(state.species.every(s => engine.normalizeSyntheticGenome(s.dna)));
const restored = life.restore(life.serialize(state));
assert.equal(restored.year, 2000);
assert.equal(restored.species.length, state.species.length);
assert.ok(restored.species.every(s => s.traits && s.form));
console.log("Planet autonomous evolution tests passed:", life.selfTest());
const earth = life.environmentFromPlanet({ id:"earth", name:"زمین", type:"terrestrial", meanTemperatureC:15, waterCoverage:0.71, gravity:1, atmosphere:"nitrogen-oxygen" });
const furnace = life.environmentFromPlanet({ id:"furnace", name:"کوره", type:"volcanic", meanTemperatureC:450, waterCoverage:0.02, gravity:1.1, atmosphere:"dense-carbon-dioxide" });
const landSpecies = { habitat:"land", traits:{ metabolicEfficiency:0.7, protection:0.6 } };
assert.ok(life.environmentSuitability(landSpecies, earth) > life.environmentSuitability(landSpecies, furnace), "extreme heat, scarce water and dense CO2 reduce habitat suitability");
const gasGiant = life.environmentFromPlanet({ id:"gas", name:"غول گازی", type:"gas-giant", meanTemperatureC:-120, waterCoverage:0.01, gravity:1.8, atmosphere:"hydrogen-helium" });
const gasState = life.createState(77, gasGiant);
assert.ok(gasState.species.every(s => s.habitat === "sky"), "gas giants use hypothetical atmospheric habitats rather than solid ground");
assert.equal(gasState.planetEnvironment.surfaceAvailable, false);
life.setEnvironment(state, furnace);
const envRestored = life.restore(life.serialize(state));
assert.equal(envRestored.planetEnvironment.planetId, "furnace");
assert.equal(envRestored.planetEnvironment.temperatureC, 450);
const legacyV1 = JSON.parse(life.serialize(state)); legacyV1.version = 1; delete legacyV1.planetEnvironment;
const migratedV1 = life.restore(legacyV1);
assert.equal(migratedV1.version, 3);
assert.equal(migratedV1.planetEnvironment.planetId, "earth");

const rolesById = new Map(state.species.map(s => [s.id, s.trophicRole]));
assert.deepEqual([1, 2, 3, 4].map(id => rolesById.get(id)), ["producer", "grazer", "predator", "decomposer"]);
assert.ok(state.resources && state.resources.shore && state.resources.ocean, "each biome has an independent resource pool");
assert.ok(Object.values(state.resources).every(r => r.biomass >= 0 && r.biomass <= r.capacity && r.nutrients >= 0), "resource cycles remain bounded");
const foodWebProbe = life.createState(42, earth);
life.advanceYears(foodWebProbe, 1);
assert.ok(foodWebProbe.events.some(e => e.kind === "predation"), "predators consume prey and record food-web events");
assert.ok(state.species.every(s => life.TROPHIC_ROLES.includes(s.trophicRole)), "every species has a trophic role");
const sameA = life.createState(20261109, earth), sameB = life.createState(20261109, earth);
life.advanceYears(sameA, 180); life.advanceYears(sameB, 180);
assert.equal(life.serialize(sameA), life.serialize(sameB), "resource and food-web simulation remains deterministic for a fixed seed");
const v2Save = JSON.parse(life.serialize(state)); v2Save.version = 2; delete v2Save.resources; delete v2Save.detritus;
const migratedV2 = life.restore(v2Save);
assert.equal(migratedV2.version, 3);
assert.ok(migratedV2.resources && migratedV2.species.every(s => s.trophicRole), "version-2 saves receive initialized ecology state");
